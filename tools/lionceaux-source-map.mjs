// Writes docs/games/SOURCE-MAP-LIONCEAUX.md from the chapter scripts of the Lionceaux game
// (app/src/games/lionceaux/chapters/chNN.ts) and the chapters of tome 1 (tome1/chapters/NN-*.md):
// for every beat, what kind it is, where it happens, what the player does, how many of the book's
// lines it shows. Run it after changing a chapter script: node tools/lionceaux-source-map.mjs
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'app/src/games/lionceaux/chapters')
const bookDir = path.join(root, 'tome1/chapters')
const fr = JSON.parse(fs.readFileSync(path.join(root, 'app/src/i18n/fr/lionceaux.json'), 'utf8'))

const files = fs.readdirSync(dir).filter((f) => /^ch\d\d\.ts$/.test(f)).sort()
const bookFile = (no) => fs.readdirSync(bookDir).find((f) => f.startsWith(String(no).padStart(2, '0') + '-'))
const front = (txt, key) => (txt.match(new RegExp(`^${key}:\\s*(.+)$`, 'm')) ?? [])[1]?.trim() ?? ''

/** The beats of a script: each `{ kind: '...', id: '...'` object, cut at the next one. */
function beats(src) {
  const re = /\{\s*kind: '(scene|play|explore|lesson)'/g
  const starts = []
  let m
  while ((m = re.exec(src))) starts.push({ at: m.index, kind: m[1] })
  return starts.map((s, i) => ({ kind: s.kind, body: src.slice(s.at, i + 1 < starts.length ? starts[i + 1].at : src.length) }))
}

const one = (body, re) => (body.match(re) ?? [])[1]
const lineCount = (body) => (body.match(/\b[NST]\(\s*(?:'[a-zA-Z]+',\s*)?"/g) ?? []).length

/** the places a script names once (const day = { id: 'bona', mood: 'golden', ... }) */
function placeConsts(src) {
  const map = {}
  for (const m of src.matchAll(/const (\w+) = \{ id: '(\w+)'(?: as const)?, mood: '(\w+)'/g)) map[m[1]] = `${m[2]} (${m[3]})`
  return map
}
function placeOf(body, consts) {
  const named = one(body, /place:\s*\{\s*id:\s*'(\w+)'/)
  if (named) { const mood = one(body, /place:\s*\{\s*id:\s*'\w+'[^}]*mood:\s*'(\w+)'/); return mood ? `${named} (${mood})` : named }
  const ref = one(body, /place:\s*(\w+)/) ?? ''
  return consts[ref] ?? ref
}
const WHO = { B: 'BriBri', K: 'Kaydoudou', R: 'Radio', M: 'Mireille', O: 'Ousmane', SA: 'Samuel', J: 'Jules', F: 'Tonton Fokou', D: 'Diego' }
const who = (id) => WHO[id] ?? id
const quote = (l) => (l.startsWith('«') ? l : `« ${l} »`)

const DOES = {
  dribble: (b) => `dribble past ${(one(b, /defenders:\s*\[([^\]]*)\]/) ?? '').split(',').filter(Boolean).length} defenders (Dribbler at the right moment)`,
  oneTouch: (b) => `one-touch pass to ${who(one(b, /to:\s*'(\w+)'/))} as the ball arrives`,
  juggle: (b) => `keep the ball up, ${one(b, /count:\s*(\d+)/)} touches in rhythm`,
  support: (b) => `two steps aside to be seen, then give it on (${one(b, /reps:\s*(\d+)/)} times)`,
  run: () => 'decoy run into the gold zone, dragging the marker',
  penalty: (b) => one(b, /role:\s*'(\w+)'/) === 'save' ? `save the penalty (canon result: ${one(b, /result:\s*'(\w+)'/)})` : `take the penalty (canon result: ${one(b, /result:\s*'(\w+)'/)})`,
  choose: (b) => {
    const opts = [...b.matchAll(/\{\s*key:\s*'(\w+)',\s*canon:\s*(true|false)/g)]
    const label = (k) => fr.choices?.[k] ?? k
    const canon = opts.filter((o) => o[2] === 'true').map((o) => label(o[1]))
    const locked = opts.filter((o) => o[2] === 'false').map((o) => label(o[1]))
    return `choose: ${canon.map(quote).join(' / ')} (canon); locked with the book's reason: ${locked.map(quote).join(', ')}`
  },
  ritual: (b) => `gesture: ${[...b.matchAll(/key:\s*'(\w+)'/g)].map((x) => quote(fr.choices?.[x[1]] ?? x[1])).join(', ')}`,
  sketch: () => 'draw the useful arrow in the notebook (between two circles, to the other side)',
  drive: () => 'carry the ball to the target',
  lure: (b) => `feint (Dribbler) to draw ${(one(b, /defenders:\s*\[([^\]]*)\]/) ?? '').split(',').filter(Boolean).length} opponents, then pass to ${who(one(b, /partner:\s*'(\w+)'/))}`,
}

let out = `# Lionceaux, le ballon qui voyage: source map

Generated by \`node tools/lionceaux-source-map.mjs\` from the chapter scripts in
\`app/src/games/lionceaux/chapters/\` and the chapters of \`tome1/chapters/\`. Do not edit by hand.

Rules the scripts follow (checked by \`chapters/verbatim.test.ts\`, which fails if any subtitle is not
found in its chapter's text): every subtitle is the book's words; a subtitle may join fragments of the
same chapter (the speech tags « dit BriBri » are left out); the outcome of every played moment is the
book's (a lost ball, a missed penalty and a lost match are played, never changed). A choice whose
other option the book's character does not take is shown and locked, with the character's own reason.
On-screen instructions (prompts, hints, button labels) are game text, written in
\`app/src/i18n/fr/lionceaux.json\`, and are never presented as the book's words.

`
for (const f of files) {
  const no = Number(f.slice(2, 4))
  const src = fs.readFileSync(path.join(dir, f), 'utf8')
  const bf = bookFile(no)
  const book = bf ? fs.readFileSync(path.join(bookDir, bf), 'utf8') : ''
  const head = (src.match(/^((?:\/\/.*\n)+)/) ?? [''])[0].split('\n').map((l) => l.replace(/^\/\/\s?/, '')).filter(Boolean)
  out += `## Chapitre ${no} : ${front(book, 'titre')} (POV ${front(book, 'pov')})\n\n`
  out += `Book: \`tome1/chapters/${bf}\`. Script: \`app/src/games/lionceaux/chapters/${f}\`.\n\n`
  if (head.length > 1) out += head.slice(1).join(' ').trim() + '\n\n'
  out += '| # | beat | kind | place | what the player does | book lines |\n|---|---|---|---|---|---|\n'
  const consts = placeConsts(src)
  let i = 0, total = 0, played = 0
  for (const b of beats(src)) {
    const id = one(b.body, /id:\s*'(\w+)'/) ?? ''
    const n = lineCount(b.body)
    total += n
    let does = ''
    if (b.kind === 'play') {
      const type = one(b.body, /type:\s*'(\w+)'/)
      does = DOES[type]?.(b.body) ?? type
      played++
    } else if (b.kind === 'explore') { does = 'walk the place and talk to the people marked'; played++ }
    else if (b.kind === 'lesson') does = `the notebook: « Leçon du Ballon n°${one(b.body, /no:\s*(\d+)/)} », then play its diagram (optional)`
    else does = /bridge:\s*true/.test(b.body) ? 'cutscene (bridge: labelled on screen as an adaptation)' : 'cutscene'
    if (/bridge:\s*true/.test(b.body) && b.kind !== 'scene') does += ' (bridge: labelled on screen as an adaptation)'
    out += `| ${++i} | ${b.kind === 'lesson' ? 'lesson' : id} | ${b.kind} | ${b.kind === 'lesson' ? '' : placeOf(b.body, consts)} | ${does} | ${n || ''} |\n`
  }
  out += `\n${i} beats, ${played} played, ${total} subtitle lines from the chapter.\n\n`
}
const target = path.join(root, 'docs/games/SOURCE-MAP-LIONCEAUX.md')
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, out)
console.log('wrote', path.relative(root, target))
