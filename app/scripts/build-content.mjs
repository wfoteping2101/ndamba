#!/usr/bin/env node
// Generates typed content modules for the app from the books' sources.
//   - src/lib/pitch.mjs            (copy of tools/pitch.mjs, the shared diagram renderer)
//   - src/content/drills.gen.ts    (the 50 drills of La Méthode Njangi, coach/drills/*.json)
//   - src/content/lessons.gen.ts   (the 40 "Leçons du Ballon" of Tome 1, tome1/chapters/*.md)
//   - src/content/books.gen.ts     (tables of contents of both books)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const APP = path.resolve(here, '..')
const ROOT = path.resolve(APP, '..')
const out = (p, s) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s) }

// 1. renderer
const pitchSrc = path.join(ROOT, 'tools', 'pitch.mjs')
if (fs.existsSync(pitchSrc)) out(path.join(APP, 'src/lib/pitch.mjs'), '// GENERATED from tools/pitch.mjs, do not edit here.\n' + fs.readFileSync(pitchSrc, 'utf8'))

// 2. drills
const drillDir = path.join(ROOT, 'coach', 'drills')
const order = ['technique', 'rondo', 'position', 'ssg', 'lsg', 'phase', 'transition', 'finishing']
let drills = []
if (fs.existsSync(drillDir)) {
  for (const f of fs.readdirSync(drillDir).filter((f) => f.endsWith('.json')).sort()) {
    try { drills.push(JSON.parse(fs.readFileSync(path.join(drillDir, f), 'utf8'))) } catch (e) { console.warn('skip drill', f, e.message) }
  }
}
drills.sort((a, b) => order.indexOf(a.family) - order.indexOf(b.family) || a.order - b.order || a.id.localeCompare(b.id))
out(path.join(APP, 'src/content/drills.gen.ts'), `// GENERATED by scripts/build-content.mjs from coach/drills/*.json. Do not edit.\nimport type { Drill } from '../lib/types'\n\nexport const DRILLS: Drill[] = ${JSON.stringify(drills, null, 1)} as Drill[]\n`)

// 3. lessons + 4. tables of contents
const parseFront = (raw) => {
  const m = raw.match(/^---\n([\s\S]*?)\n---\n/)
  const meta = {}
  if (m) for (const line of m[1].split('\n')) { const k = line.match(/^(\w+):\s*(.*)$/); if (k) meta[k[1]] = k[2].trim() }
  return { meta, body: m ? raw.slice(m[0].length) : raw }
}
const lessons = []
const tome1 = []
const t1dir = path.join(ROOT, 'tome1', 'chapters')
if (fs.existsSync(t1dir)) {
  for (const f of fs.readdirSync(t1dir).filter((f) => /^\d\d-.*\.md$/.test(f)).sort()) {
    const { meta, body } = parseFront(fs.readFileSync(path.join(t1dir, f), 'utf8'))
    tome1.push({ no: Number(meta.numero), slug: meta.slug, title: meta.titre, part: Number(meta.partie), pov: meta.pov, summary: meta.resume })
    const box = body.match(/^> \[!CARNET\][^\n]*\n(?:>.*\n?)*/m)
    if (!box) continue
    const lines = box[0].split('\n').filter(Boolean)
    const head = lines[0].replace(/^> \[!CARNET\]\s*/, '')
    const title = head.replace(/^Leçon du Ballon n°\s*\d+\s*:\s*/i, '').trim()
    const text = lines.slice(1).map((l) => l.replace(/^>\s?/, '').trim()).filter(Boolean)
    const sm = body.match(/```schema\n([\s\S]*?)```/)
    let diagram = null
    if (sm) { try { diagram = JSON.parse(sm[1]) } catch { diagram = null } }
    lessons.push({ no: Number(meta.numero), part: Number(meta.partie), chapterTitle: meta.titre, title, lines: text, diagram })
  }
}
out(path.join(APP, 'src/content/lessons.gen.ts'), `// GENERATED by scripts/build-content.mjs from tome1/chapters/*.md. Do not edit.\nimport type { Lesson } from '../lib/types'\n\nexport const LESSONS: Lesson[] = ${JSON.stringify(lessons, null, 1)} as Lesson[]\n`)

const methode = []
const cdir = path.join(ROOT, 'coach', 'chapters')
if (fs.existsSync(cdir)) {
  for (const f of fs.readdirSync(cdir).filter((f) => /^\d\d-.*\.md$/.test(f)).sort()) {
    const { meta } = parseFront(fs.readFileSync(path.join(cdir, f), 'utf8'))
    methode.push({ no: Number(meta.numero), slug: meta.slug, title: meta.titre, part: Number(meta.partie), partTitle: meta.titrePartie, summary: meta.resume })
  }
}
out(path.join(APP, 'src/content/books.gen.ts'), `// GENERATED by scripts/build-content.mjs. Do not edit.\nexport interface TocEntry { no: number; slug: string; title: string; part: number; partTitle?: string; pov?: string; summary?: string }\nexport const TOME1_TOC: TocEntry[] = ${JSON.stringify(tome1, null, 1)}\nexport const METHODE_TOC: TocEntry[] = ${JSON.stringify(methode, null, 1)}\n`)

console.log(`content: ${drills.length} drills, ${lessons.length} lessons, ${tome1.length} + ${methode.length} chapters`)
