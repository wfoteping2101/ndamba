#!/usr/bin/env node
// Generates typed content modules for the app from the books' sources.
//   - src/lib/pitch.mjs            (copy of tools/pitch.mjs, the shared diagram renderer)
//   - src/content/drills.gen.ts    (the 50 drills of La Méthode Njangi, coach/drills/*.json)
//   - src/content/lessons.gen.ts   (the 40 "Leçons du Ballon" of Tome 1, tome1/chapters/*.md)
//   - src/content/books.gen.ts     (tables of contents of both books)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const APP = path.resolve(here, '..')
const ROOT = path.resolve(APP, '..')
const out = (p, s) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s) }

// 1. renderer
const pitchSrc = path.join(ROOT, 'tools', 'pitch.mjs')
if (fs.existsSync(pitchSrc)) out(path.join(APP, 'src/lib/pitch.mjs'), '// GENERATED from tools/pitch.mjs, do not edit here.\n' + fs.readFileSync(pitchSrc, 'utf8'))

// 2. drills
const drillDir = path.join(ROOT, 'coach', 'drills')
const order = ['technique', 'rondo', 'position', 'ssg', 'lsg', 'phase', 'transition', 'finishing']
let drills = []
if (fs.existsSync(drillDir)) {
  for (const f of fs.readdirSync(drillDir).filter((f) => f.endsWith('.json')).sort()) {
    try { drills.push(JSON.parse(fs.readFileSync(path.join(drillDir, f), 'utf8'))) } catch (e) { console.warn('skip drill', f, e.message) }
  }
}
drills.sort((a, b) => order.indexOf(a.family) - order.indexOf(b.family) || a.order - b.order || a.id.localeCompare(b.id))
out(path.join(APP, 'src/content/drills.gen.ts'), `// GENERATED by scripts/build-content.mjs from coach/drills/*.json. Do not edit.\nimport type { Drill } from '../lib/types'\n\nexport const DRILLS: Drill[] = ${JSON.stringify(drills, null, 1)} as Drill[]\n`)

// 3. lessons + 4. tables of contents
const parseFront = (raw) => {
  const m = raw.match(/^---\n([\s\S]*?)\n---\n/)
  const meta = {}
  if (m) for (const line of m[1].split('\n')) { const k = line.match(/^(\w+):\s*(.*)$/); if (k) meta[k[1]] = k[2].trim() }
  return { meta, body: m ? raw.slice(m[0].length) : raw }
}
const lessons = []
const tome1 = []
const t1dir = path.join(ROOT, 'tome1', 'chapters')
if (fs.existsSync(t1dir)) {
  for (const f of fs.readdirSync(t1dir).filter((f) => /^\d\d-.*\.md$/.test(f)).sort()) {
    const { meta, body } = parseFront(fs.readFileSync(path.join(t1dir, f), 'utf8'))
    tome1.push({ no: Number(meta.numero), slug: meta.slug, title: meta.titre, part: Number(meta.partie), pov: meta.pov, summary: meta.resume })
    const box = body.match(/^> \[!CARNET\][^\n]*\n(?:>.*\n?)*/m)
    if (!box) continue
    const lines = box[0].split('\n').filter(Boolean)
    const head = lines[0].replace(/^> \[!CARNET\]\s*/, '')
    const title = head.replace(/^Leçon du Ballon n°\s*\d+\s*:\s*/i, '').trim()
    const text = lines.slice(1).map((l) => l.replace(/^>\s?/, '').trim()).filter(Boolean)
    const sm = body.match(/```schema\n([\s\S]*?)```/)
    let diagram = null
    if (sm) { try { diagram = JSON.parse(sm[1]) } catch { diagram = null } }
    lessons.push({ no: Number(meta.numero), part: Number(meta.partie), chapterTitle: meta.titre, title, lines: text, diagram })
  }
}
out(path.join(APP, 'src/content/lessons.gen.ts'), `// GENERATED by scripts/build-content.mjs from tome1/chapters/*.md. Do not edit.\nimport type { Lesson } from '../lib/types'\n\nexport const LESSONS: Lesson[] = ${JSON.stringify(lessons, null, 1)} as Lesson[]\n`)

const methode = []
const cdir = path.join(ROOT, 'coach', 'chapters')
if (fs.existsSync(cdir)) {
  for (const f of fs.readdirSync(cdir).filter((f) => /^\d\d-.*\.md$/.test(f)).sort()) {
    const { meta } = parseFront(fs.readFileSync(path.join(cdir, f), 'utf8'))
    methode.push({ no: Number(meta.numero), slug: meta.slug, title: meta.titre, part: Number(meta.partie), partTitle: meta.titrePartie, summary: meta.resume })
  }
}
out(path.join(APP, 'src/content/books.gen.ts'), `// GENERATED by scripts/build-content.mjs. Do not edit.\nexport interface TocEntry { no: number; slug: string; title: string; part: number; partTitle?: string; pov?: string; summary?: string }\nexport const TOME1_TOC: TocEntry[] = ${JSON.stringify(tome1, null, 1)}\nexport const METHODE_TOC: TocEntry[] = ${JSON.stringify(methode, null, 1)}\n`)

// 5. Lionceaux tome 1 artwork, for the review page (/revue): only the files already published in
//    public/book/tome1/img/, with their French alt texts from tome1/art/inventory.json, their review
//    notes (tome1/art/review.json), and the art direction (tome1/art/ART_DIRECTION.md) as plain sections.
const IMG = path.join(APP, 'public', 'book', 'tome1', 'img')
const ART = path.join(ROOT, 'tome1', 'art')
const readJson = (p, fallback) => { try { return JSON.parse(fs.readFileSync(p, 'utf8')) } catch { return fallback } }
const inventory = readJson(path.join(ART, 'inventory.json'), [])
const review = readJson(path.join(ART, 'review.json'), {})
/** Width and height of a JPEG, from its SOF marker (no dependency). */
const jpegSize = (file) => {
  try {
    const b = fs.readFileSync(file)
    let i = 2
    while (i + 9 < b.length) {
      if (b[i] !== 0xff) { i++; continue }
      const m = b[i + 1]
      const len = b.readUInt16BE(i + 2)
      if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) return { h: b.readUInt16BE(i + 5), w: b.readUInt16BE(i + 7) }
      i += 2 + len
    }
  } catch { /* unreadable: no size */ }
  return null
}
// published file name -> inventory id (the reader names three images differently)
const FILE_ID = { cover: 'cover-art', characters: 'sheet-brothers', family: 'sheet-adults' }
const beatIds = (n) => inventory.filter((a) => a.kind === 'beat' && a.chapter === n).map((a) => a.id).sort()
// per chapter: the opener, then its in-text beats (3 per chapter once planned)
const planned = ['cover', 'characters', 'family', ...[1, 2, 3, 4, 5].map((n) => `part${n}`), ...Array.from({ length: 40 }, (_, i) => [`ch${String(i + 1).padStart(2, '0')}`, ...beatIds(i + 1)]).flat()]
const plannedTotal = 3 + 5 + 40 * 4
const art = []
const isBeatFile = (f) => /^ch\d\d[b-z]$/.test(f)
for (const file of planned) {
  const jpg = path.join(IMG, `${file}.jpg`)
  if (!fs.existsSync(jpg)) continue
  const id = FILE_ID[file] || file
  const inv = inventory.find((a) => a.id === id) || {}
  const size = jpegSize(jpg) || (isBeatFile(file) ? { w: 1536, h: 1024 } : { w: 1024, h: 1536 })
  const ch = /^ch(\d\d)[b-z]?$/.exec(file), pt = /^part(\d)$/.exec(file), isBeat = /^ch\d\d[b-z]$/.test(file)
  const toc = ch ? tome1.find((c) => c.no === Number(ch[1])) : null
  art.push({
    file, id, kind: file === 'cover' ? 'cover' : pt ? 'part' : isBeat ? 'beat' : ch ? 'chapter' : 'sheet',
    chapter: ch ? Number(ch[1]) : null, part: pt ? Number(pt[1]) : ch ? (toc?.part ?? inv.part ?? null) : null,
    title: inv.title || toc?.title || null, alt: inv.alt || '', w: size.w, h: size.h,
    thumb: fs.existsSync(path.join(IMG, `${file}-480.jpg`)), webp: fs.existsSync(path.join(IMG, `${file}.webp`)) && fs.existsSync(path.join(IMG, `${file}-480.webp`)),
    status: review[id]?.status || null, note: review[id]?.note || null,
  })
}
const sections = []
const adPath = path.join(ART, 'ART_DIRECTION.md')
if (fs.existsSync(adPath)) {
  const plain = (s) => s.replace(/\*\*(.+?)\*\*/g, '$1').replace(/`([^`]+)`/g, '$1').replace(/\s+/g, ' ').trim()
  let cur = null
  for (const line of fs.readFileSync(adPath, 'utf8').split('\n')) {
    const h = line.match(/^##\s+(.*)$/)
    if (h) { cur = { title: plain(h[1].replace(/^\d+\.\s*/, '')), blocks: [] }; sections.push(cur); continue }
    if (!cur || !line.trim() || /^#\s/.test(line)) continue
    const li = line.match(/^\s*(?:[-*]|\d+\.)\s+(.*)$/)
    if (line.startsWith('>')) cur.blocks.push({ type: 'quote', text: plain(line.replace(/^>\s?/, '')) })
    else if (li) cur.blocks.push({ type: 'li', text: plain(li[1]) })
    else cur.blocks.push({ type: 'p', text: plain(line) })
  }
}
out(path.join(APP, 'src/content/art.gen.ts'), `// GENERATED by scripts/build-content.mjs from public/book/tome1/img/ and tome1/art/. Do not edit.
export interface ArtImage { file: string; id: string; kind: 'cover' | 'sheet' | 'part' | 'chapter' | 'beat'; chapter: number | null; part: number | null; title: string | null; alt: string; w: number; h: number; thumb: boolean; webp: boolean; status: string | null; note: string | null }
export interface ArtSection { title: string; blocks: { type: 'p' | 'li' | 'quote'; text: string }[] }
/** Illustrations planned for tome 1: cover, two character pages, five part openers, forty chapter openers and three in-text images per chapter. */
export const TOME1_ART_PLANNED = ${plannedTotal}
export const TOME1_ART: ArtImage[] = ${JSON.stringify(art, null, 1)}
export const ART_DIRECTION: ArtSection[] = ${JSON.stringify(sections, null, 1)}
`)

console.log(`content: ${drills.length} drills, ${lessons.length} lessons, ${tome1.length} + ${methode.length} chapters, ${art.length} of ${plannedTotal} illustrations`)
